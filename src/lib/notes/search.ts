/**
 * Пользовательский запрос → выражение `tsquery`.
 *
 * Почему не `plainto_tsquery` из Postgres: он не умеет префиксного поиска, а
 * в тетради ищут по началу слова гораздо чаще, чем по точной форме («интерл»
 * должно находить «интерливинг»). Конфигурация индекса — `simple`, без
 * стемминга (тетрадь многоязычна), поэтому без префикса поиск находил бы
 * только точное совпадение словоформы.
 *
 * Чистая функция: разбор запроса — самое хрупкое место поиска, и проверяться
 * он должен тестом, а не запросами к живой базе. Экранирование здесь же —
 * `tsquery` имеет собственный синтаксис (`&`, `|`, `!`, `:*`, скобки), и
 * невалидное выражение роняет запрос ошибкой Postgres, а не пустым ответом.
 */

/** Кавычки — фраза целиком; остальное — отдельные слова. */
const PHRASE = /"([^"]+)"/g;

function sanitizeTerm(term: string): string {
  // Оставляем буквы/цифры любого алфавита: латиница, кириллица, испанские
  // диакритики. Всё остальное — синтаксис tsquery или пунктуация.
  return term.replace(/[^\p{L}\p{N}_-]+/gu, ' ').trim();
}

/**
 * `null` — запрос пуст после очистки. Это не ошибка: вызывающий код просто не
 * применяет фильтр поиска, а не показывает пустой список.
 */
export function toTsQuery(input: string): string | null {
  const phrases: string[] = [];
  const rest = input.replace(PHRASE, (_match, phrase: string) => {
    const words = sanitizeTerm(phrase).split(/\s+/).filter(Boolean);
    // Фраза — соседство слов: оператор `<->` («followed by»).
    if (words.length > 0) phrases.push(words.join(' <-> '));
    return ' ';
  });

  const words = sanitizeTerm(rest)
    .split(/\s+/)
    .filter(Boolean)
    // Префиксный поиск на каждое слово: `интерл:*`.
    .map((word) => `${word}:*`);

  const parts = [...phrases, ...words];
  if (parts.length === 0) return null;

  // Все слова обязательны (`&`), а не любое из них: при поиске по собственной
  // тетради человек уточняет запрос, добавляя слова, и ждёт сужения выдачи.
  return parts.join(' & ');
}
