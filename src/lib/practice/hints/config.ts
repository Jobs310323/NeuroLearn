/**
 * Пороги правил подсказок.
 *
 * Вынесены в конфиг с умолчаниями намеренно, а не захардкожены по месту:
 * это заявленная точка расширения. Через месяц накопленных `hint_events`
 * пороги пересматриваются по данным — сколько подсказок каждого типа
 * показано, сколько закрыто не глядя, сколько привело к действию. Пока
 * значения — обоснованные догадки, и называть их иначе было бы нечестно.
 *
 * Числа ниже — не результат измерений на пользователях этого продукта.
 * Каждое сопровождается тем, из чего оно взято.
 */
export const HINT_THRESHOLDS = {
  rest: {
    /**
     * Насколько должна вырасти скользящая медиана времени ответа, чтобы
     * предложить перерыв. 40% — заметный на глаз спад темпа, но ещё не
     * «человек ушёл от экрана».
     */
    slowdownRatio: 0.4,
    /** База сравнения: первые задания сессии, пока темп ровный. */
    baselineItems: 5,
    /** Раньше восьмого задания разговор об усталости преждевременен. */
    minItems: 8,
    /** Окно скользящей медианы. */
    windowItems: 5,
    /** Длительность предлагаемого перерыва. Запускает его человек, не система. */
    restSeconds: 120,
  },
  metacognition: {
    /** Уверенность, начиная с которой ошибка читается как «не знал, что не знаю». */
    minConfidence: 4,
  },
  contrast: {
    /** Сколько ошибок подряд по соседним узлам считаем закономерностью. */
    minErrors: 2,
    /** В каком окне последних заданий их искать. */
    windowItems: 5,
  },
  difficulty: {
    /**
     * Уровень Блума (1..5 по шкале чипа), с которого один раз за сессию
     * сообщаем, что можно запросить наводящую подсказку.
     */
    offerHintFromLevel: 4,
  },
  review: {
    /** Максимум заметок «перечитать перед практикой». Больше — это уже чтение, а не разминка. */
    maxNotes: 2,
  },
} as const;

/**
 * Шкала сложности по Блуму 1..5 для чипа в интерфейсе.
 *
 * `create` и `evaluate` делят верхнюю ступень: для человека за экраном они
 * одинаково «самое сложное», а различать их чипом — точность, которой он не
 * несёт.
 */
export const BLOOM_DIFFICULTY: Record<string, number> = {
  recall: 1,
  understand: 2,
  apply: 3,
  analyze: 4,
  evaluate: 5,
  create: 5,
};

export function bloomDifficulty(level: string | null): number | null {
  if (!level) return null;
  return BLOOM_DIFFICULTY[level] ?? null;
}
