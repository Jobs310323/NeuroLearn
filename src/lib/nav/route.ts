import type { Route } from 'next';

/**
 * Приведение строки к типизированному маршруту.
 *
 * `typedRoutes` в Next проверяет литералы и шаблоны, которые может доказать
 * статически. Адреса, пришедшие с сервера (выдача поиска, действия подсказок),
 * для него просто `string` — доказать он ничего не может, и приведение
 * неизбежно.
 *
 * Функция существует, чтобы приведение было ОДНО и с объяснением, а не
 * россыпью `as never` по обработчикам. Условие безопасности: сюда попадают
 * только адреса, собранные нашим же кодом из закрытого набора шаблонов
 * (`/notes?note=…`, `/paths/…`, `/tutor?…`). Пользовательский ввод сюда
 * попадать не должен — открытый редирект начинается ровно так.
 */
export function toRoute(href: string): Route {
  return href as Route;
}
