/**
 * Определение активного пункта навигации.
 *
 * Вынесено из компонента отдельным модулем без импортов: правило простое, но
 * ошибка в нём («активный пункт не подсвечивается» или подсвечиваются два
 * сразу) видна пользователю на каждом экране, поэтому проверяется юнит-тестом
 * без рендера.
 *
 * Активен либо сам раздел, либо любая вложенная страница: со страницы
 * `/paths/<id>` пункт «Пути» обязан оставаться подсвеченным. Сравнение идёт по
 * границе сегмента, иначе `/notebook` активировал бы `/notes`.
 */
export function isActiveNav(pathname: string, href: string): boolean {
  if (href === pathname) return true;
  return pathname.startsWith(`${href}/`);
}
