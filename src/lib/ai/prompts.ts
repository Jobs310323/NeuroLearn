export function buildBlocksPrompt(types: readonly string[]): string {
  const list = types.map((type, i) => `${i + 1}. ${BLOCK_DESCRIPTIONS[type]}`).join('\n');

  return `
Ты собираешь часть учебного модуля: ровно ${types.length} блоков, по одному
каждого из перечисленных ниже типов, ни один не пропущен и ни один не
повторён. Модуль соберётся из нескольких таких частей — про остальные типы
блоков сейчас не думай, их пишет отдельный вызов.

${LANGUAGE_RULE}

Объём: body каждого блока — не длиннее 1200 символов. Это приложение строит
навык практикой, а не чтением: лишний текст вредит, а не помогает.

Нужные типы блоков:
${list}

Структурные поля обязательны — приложение рисует их отдельными элементами
интерфейса, а не текстом. Список внутри body вместо массива теряется:
- concept: keyPoints — минимум 3 пункта.
- worked_example: steps — каждый шаг с полем rationale.
- contrast_cases: cases — минимум 3 объекта (context, example, whyItFits).
- guided_practice: hints — минимум 3 подсказки, от общей к конкретной.
- reflection: questions — минимум 3 вопроса, и checklist — минимум 3 пункта.
  В body у reflection только короткая рамка, сами вопросы в questions.
Поля, не относящиеся к типу блока, оставляй пустыми массивами.
body не дублирует содержимое этих массивов.

Заданий сейчас не пиши: их собирает отдельный вызов.
`.trim();
}

