/**
 * Индекс усталости внутри сессии — коэффициент вариации времени ответа
 * по верным ответам.
 *
 * Фаза 1, пункт 12 плана: только в аналитику, без влияния на подбор.
 * Причина не в осторожности ради осторожности: коэффициент вариации — эвристика,
 * а не измерение, и прежде чем на него опираться при выборе заданий, нужно
 * увидеть его на собственных данных хотя бы месяц и убедиться, что он
 * действительно растёт к концу длинных сессий, а не просто шумит. Пока это
 * наблюдение, а не решение (используется в Фазе 2 — `decidePolicy` его
 * намеренно не читает, см. комментарий там).
 *
 * Рост дисперсии при неизменной точности — правдоподобный признак усталости:
 * человек ещё отвечает верно, но темп перестаёт быть ровным. Считается
 * только по верным ответам: время неверного — это время колебаний и
 * пересмотра решения, а не темп извлечения из памяти.
 */

export type FatigueSample = { responseTimeMs: number; isCorrect: boolean };

/** Меньше — коэффициент вариации на таком количестве точек не значит ничего. */
const MIN_SAMPLES = 5;

export function responseTimeVariability(samples: FatigueSample[]): number | null {
  const times = samples.filter((s) => s.isCorrect).map((s) => s.responseTimeMs);
  if (times.length < MIN_SAMPLES) return null;

  const mean = times.reduce((a, b) => a + b, 0) / times.length;
  if (mean === 0) return null;

  const variance = times.reduce((sum, t) => sum + (t - mean) ** 2, 0) / times.length;
  return Math.sqrt(variance) / mean;
}
