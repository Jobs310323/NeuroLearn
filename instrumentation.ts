/**
 * Точка инициализации серверного рантайма Next (вызывается один раз при
 * старте сервера, до обработки первого запроса).
 *
 * Здесь включается только маршрутизация исходящих запросов через прокси из
 * переменных окружения — см. `src/lib/net/proxy.ts`. Нужно для разработки на
 * машине с локальным прокси: иначе вызовы к провайдерам моделей идут напрямую
 * и получают 403. На Vercel переменных прокси нет и вызов ничего не делает.
 */
export async function register(): Promise<void> {
  // Edge-рантайм не даёт менять сетевой стек и в прокси не нуждается.
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;

  const { enableEnvProxy } = await import('@/lib/net/proxy');
  enableEnvProxy();
}
